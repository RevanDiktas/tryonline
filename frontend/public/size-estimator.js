// The build questions. Each is a three-way self-assessment against "people of my height and
// weight", and moves one measurement. Men: chest and belly. Women: bust and hips.
export const SHAPE_QUESTIONS = {
  male: [
    { id: 'chest', target: 'chest', label: 'Chest and shoulders', options: ['Slimmer', 'Average', 'Broader'] },
    { id: 'belly', target: 'waist', label: 'Belly', options: ['Flatter', 'Average', 'Rounder'] },
  ],
  female: [
    { id: 'chest', target: 'chest', label: 'Bust', options: ['Smaller', 'Average', 'Fuller'] },
    { id: 'hips', target: 'hips', label: 'Hips', options: ['Narrower', 'Average', 'Wider'] },
  ],
};
SHAPE_QUESTIONS.unisex = SHAPE_QUESTIONS.female.map((q) => (q.id === 'chest' ? { ...q, label: 'Chest' } : q));

// ASSUMPTION, not measured: how far a shopper's own answer moves the estimate, as a fraction
// of the true lower/upper-third shift. People judge their own build imperfectly, so an
// answer moves the estimate 60% of the way and never the whole way. There is no data yet on
// how well shoppers self-assess; revisit once size-finder orders and returns can be compared.
export const SHAPE_WEIGHT = 0.6;

export const INPUT_LIMITS = { height: [120, 230], weight: [30, 250], age: [14, 100] };

const TARGETS = ['chest', 'waist', 'hips'];

function num(v) {
  const n = typeof v === 'string' ? parseFloat(v.replace(',', '.')) : v;
  return typeof n === 'number' && isFinite(n) ? n : null;
}

/** 'female' | 'male' | 'unisex' from whatever the caller has. */
export function normalizeGender(g) {
  const s = String(g || '').toLowerCase();
  if (s === 'female' || s === 'woman' || s === 'women' || s === 'f') return 'female';
  if (s === 'male' || s === 'man' || s === 'men' || s === 'm') return 'male';
  return 'unisex';
}

/** null when the input is usable, otherwise a message for the shopper. */
export function validateInput(input) {
  const h = num(input && input.height);
  const w = num(input && input.weight);
  const a = input && input.age != null && input.age !== '' ? num(input.age) : undefined;
  if (h == null || h < INPUT_LIMITS.height[0] || h > INPUT_LIMITS.height[1]) return 'Enter your height.';
  if (w == null || w < INPUT_LIMITS.weight[0] || w > INPUT_LIMITS.weight[1]) return 'Enter your weight.';
  if (a === null || (a !== undefined && (a < INPUT_LIMITS.age[0] || a > INPUT_LIMITS.age[1]))) return 'Check your age, or leave it empty.';
  return null;
}

function answerIndex(v) {
  // -1 slimmer / 0 average / +1 fuller. Accepts -1|0|1 or 'low'|'mid'|'high'.
  if (v === -1 || v === 'low') return -1;
  if (v === 1 || v === 'high') return 1;
  return 0;
}

function estimateOne(model, height, weight, age, shape) {
  const variant = age == null ? 'noage' : 'age';
  const mean = {};
  const sd = {};
  for (const t of TARGETS) {
    const c = model[t][variant].coef;
    mean[t] = c[0] + c[1] * height + c[2] * weight + (age == null ? 0 : c[3] * age);
    sd[t] = model[t][variant].sd;
  }
  // Build answers: move the measurement they are about, and nudge the others the way they
  // move for people who really are in that third.
  const answered = {};
  for (const t of TARGETS) {
    const a = shape[t];
    if (a === undefined) continue;
    answered[t] = true;
    const side = answerIndex(a);
    if (side !== 0) {
      const i = side < 0 ? 0 : 1;
      mean[t] += SHAPE_WEIGHT * model[t].shift[i];
      for (const o of Object.keys(model[t].cross)) {
        if (shape[o] === undefined) mean[o] += SHAPE_WEIGHT * model[t].cross[o][i];
      }
    }
  }
  // An answer narrows the error, but only part of the way to what a perfect answer would:
  // halfway between "no answer" and "a correct answer moved by SHAPE_WEIGHT".
  for (const t of TARGETS) {
    if (!answered[t]) continue;
    const s = (Math.abs(model[t].shift[0]) + Math.abs(model[t].shift[1])) / 2;
    const ifCorrect = Math.sqrt(model[t].within ** 2 + (2 / 3) * ((1 - SHAPE_WEIGHT) * s) ** 2);
    sd[t] = (sd[t] + ifCorrect) / 2;
  }
  return { mean, sd };
}

/**
 * Estimate chest, waist and hips (cm).
 *
 * input: { gender, height (cm), weight (kg), age?, shape?: { chest?, belly?, hips? } }
 *        shape answers are -1 (slimmer) / 0 (average) / 1 (fuller); leave a key out when
 *        the question was not asked.
 * returns { gender, measurements, sd, extrapolated, usedAge } or null for unusable input.
 *        measurements.waist is absent unless gender is male (see LIMITS at the top).
 */
export function estimateBody(input) {
  if (validateInput(input)) return null;
  const gender = normalizeGender(input.gender);
  const height = num(input.height);
  const weight = num(input.weight);
  const rawAge = input.age != null && input.age !== '' ? num(input.age) : null;
  const sh = input.shape || {};
  const shape = {};
  if (sh.chest !== undefined) shape.chest = sh.chest;
  if (sh.belly !== undefined) shape.waist = sh.belly;
  if (sh.hips !== undefined) shape.hips = sh.hips;

  const models = gender === 'unisex' ? [MODEL.male, MODEL.female] : [MODEL[gender]];
  let extrapolated = false;
  const parts = models.map((model) => {
    const r = model.range;
    // Age is held at the edge of the sample: the fit's age slope is not evidence about a
    // 75-year-old. Height and weight outside the sample are used as given, and flagged.
    const age = rawAge == null ? null : Math.max(r.age[0], Math.min(r.age[1], rawAge));
    if (height < r.height[0] || height > r.height[1] || weight < r.weight[0] || weight > r.weight[1]
        || (rawAge != null && age !== rawAge)) {
      extrapolated = true;
    }
    return estimateOne(model, height, weight, age, shape);
  });

  const measurements = { height };
  const sd = {};
  for (const t of TARGETS) {
    const means = parts.map((p) => p.mean[t]);
    const m = means.reduce((a, b) => a + b, 0) / means.length;
    let s = Math.max(...parts.map((p) => p.sd[t]));
    // Not knowing which model applies is itself error: add half the gap between the two.
    if (parts.length === 2) s = Math.sqrt(s ** 2 + ((means[0] - means[1]) / 2) ** 2);
    if (extrapolated) s *= 1.5;
    measurements[t] = Math.round(m * 10) / 10;
    sd[t] = Math.round(s * 100) / 100;
  }
  if (gender !== 'male') {
    delete measurements.waist;
    delete sd.waist;
  }
  return { gender, measurements, sd, extrapolated, usedAge: rawAge != null };
}

// Standard normal quantile (Acklam's approximation; error < 1.2e-9, plenty here).
function normalQuantile(p) {
  const a = [-39.69683028665376, 220.9460984245205, -275.9285104469687, 138.357751867269, -30.66479806614716, 2.506628277459239];
  const b = [-54.47609879822406, 161.5858368580409, -155.6989798598866, 66.80131188771972, -13.28068155288572];
  const c = [-0.007784894002430293, -0.3223964580411365, -2.400758277161838, -2.549732539343734, 4.374664141464968, 2.938163982698783];
  const d = [0.007784695709041462, 0.3224671290700398, 2.445134137142996, 3.754408661907416];
  const lo = 0.02425;
  if (p < lo) {
    const q = Math.sqrt(-2 * Math.log(p));
    return (((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) / ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1);
  }
  if (p > 1 - lo) {
    const q = Math.sqrt(-2 * Math.log(1 - p));
    return -(((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) / ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1);
  }
  const q = p - 0.5;
  const r = q * q;
  return (((((a[0] * r + a[1]) * r + a[2]) * r + a[3]) * r + a[4]) * r + a[5]) * q / (((((b[0] * r + b[1]) * r + b[2]) * r + b[3]) * r + b[4]) * r + 1);
}

const QUANTILE_STEPS = 41;
// A second size is worth mentioning when it is this likely.
export const BETWEEN_SIZES_AT = 0.25;

/**
 * Recommend a size for one product from a quick body estimate.
 *
 * input    as estimateBody
 * product  { sizes: string[], sizeChart?, category?, fitType?, convention? }
 *          `sizes` are the store's own size labels for this product. A chart is optional:
 *          the engine sizes from the body when there is none.
 * opts     { preferredFit?: 'slim'|'regular'|'loose', country? }
 *
 * returns null for unusable input or a product with no sizes, otherwise
 *   { recommendedSize, confidence (0-100: chance this is the size a tape measure would
 *     give), probabilities: [{ size, p }] most likely first, alternative (a second size at
 *     least BETWEEN_SIZES_AT likely, or null), anchor ('chest'|'waist'|'hips'),
 *     measurements, sd, extrapolated, reasoning }
 */
export function quickSize(input, product, opts) {
  const est = estimateBody(input);
  const sizes = ((product && product.sizes) || []).map((s) => String(s)).filter((s) => s.trim());
  if (!est || sizes.length === 0) return null;
  const o = opts || {};
  const p = product || {};
  const category = p.category || 'tops';
  const run = (meas) => recommendSize(
    meas, p.sizeChart || {}, o.preferredFit || 'regular', category, p.fitType || 'regular',
    p.convention || 'circumference', est.gender, sizes, o.country,
  );

  const base = run(est.measurements);

  // The engine anchors on one measurement per category (waist falls back to hips).
  let anchor = CATEGORY_ANCHOR[category] || 'chest';
  if (est.measurements[anchor] == null) anchor = anchor === 'waist' ? 'hips' : 'waist';

  // Spread: re-run the engine across the estimate's error and count what it picks. Going
  // through the engine (rather than reading size bands here) keeps height bumps, fit
  // preference and clamping to the product's sizes exactly as the engine applies them.
  const tally = {};
  for (let i = 0; i < QUANTILE_STEPS; i++) {
    const z = normalQuantile((i + 0.5) / QUANTILE_STEPS);
    const shifted = { ...est.measurements };
    for (const k of Object.keys(est.sd)) shifted[k] = est.measurements[k] + z * est.sd[k];
    const pick = run(shifted).recommendedSize;
    tally[pick] = (tally[pick] || 0) + 1;
  }
  const probabilities = Object.keys(tally)
    .map((size) => ({ size, p: Math.round((tally[size] / QUANTILE_STEPS) * 100) / 100 }))
    .sort((x, y) => y.p - x.p);

  const recommendedSize = base.recommendedSize;
  const own = probabilities.find((x) => x.size === recommendedSize);
  const confidence = Math.round((own ? own.p : 0) * 100);
  const second = probabilities.find((x) => x.size !== recommendedSize && x.p >= BETWEEN_SIZES_AT);

  return {
    recommendedSize,
    confidence,
    probabilities,
    alternative: second ? second.size : null,
    anchor,
    measurements: est.measurements,
    sd: est.sd,
    extrapolated: est.extrapolated,
    reasoning: quickReasoning(recommendedSize, second ? second.size : null, sizes, o.preferredFit || 'regular', est.extrapolated),
  };
}

function label(size) {
  return String(size).toUpperCase();
}

/** One or two plain sentences for the result card. */
export function quickReasoning(size, alternative, sizes, preferredFit, extrapolated) {
  const parts = [];
  if (alternative) {
    const order = sizes.map((s) => String(s));
    const bigger = order.indexOf(alternative) > order.indexOf(size);
    parts.push(
      'You are between ' + label(bigger ? size : alternative) + ' and ' + label(bigger ? alternative : size) + '. '
      + 'Take ' + label(bigger ? size : alternative) + ' for a closer fit, ' + label(bigger ? alternative : size) + ' for more room.',
    );
  } else if (preferredFit === 'regular') {
    parts.push('People with your height, weight and build most often wear ' + label(size) + '.');
  } else {
    parts.push('We picked ' + label(size) + ' because you like a ' + (preferredFit === 'slim' ? 'closer' : 'looser') + ' fit.');
  }
  if (extrapolated) parts.push('Your height, weight or age is outside what this estimate was built on, so treat it as a rough guide.');
  return parts.join(' ');
}

