/**
 * Size finder: a size without an avatar.
 *
 * The avatar try-on measures a shopper from a photo. That takes minutes and needs the
 * product to have a 3D garment. This estimates the same three body measurements from what
 * a shopper can type in ten seconds (height, weight, optionally age, and two taps about
 * their build), then hands them to the SAME sizing engine (sizing-engine.js), so both
 * tiers pick sizes by one set of rules. It works on any product that has sizes.
 *
 * Plain ES module, no framework, like sizing-engine.js: used by the store-page size finder
 * (size-finder.html) and importable from the Next app.
 *
 * WHAT IT IS NOT. It is an estimate with a known error, not a measurement. From height,
 * weight and age alone it lands on the same size as a tape measure about two times in
 * three, and within one size about 99 times in 100 (see ACCURACY below). So the result
 * always carries a probability per size, and says so when a shopper is between two.
 *
 * WHERE THE NUMBERS COME FROM. scripts/fit_size_estimator.py fits them on ANSUR II, the
 * public US Army body survey (4,081 men and 1,986 women, measured 2010-2012), using the
 * self-reported height and weight columns as inputs: people overstate their height and
 * understate their weight, and fitting on their own answers absorbs that.
 *
 * LIMITS.
 *  - Soldiers aged 17-58 are leaner and more muscular than shoppers in general. The build
 *    questions partly correct for that; outside the sampled range the estimate is an
 *    extrapolation, flagged as `extrapolated` and given a wider error.
 *  - ANSUR's waist is measured at the navel. That matches where men's trousers sit. It is
 *    NOT the natural waist women's size charts use, so no waist is estimated for women:
 *    their bottoms are sized from the hips, which the engine already supports.
 */

