// Checked in order: the first group with a matching word wins. Words are matched whole, in
// lower case, against the Shopify product type and title (English, Dutch, German, French).
const CATEGORY_WORDS = [
  ['accessories', ['cap', 'caps', 'hat', 'beanie', 'bag', 'tote', 'totebag', 'sock', 'socks', 'scarf', 'belt', 'pet', 'muts', 'tas', 'riem', 'sjaal', 'sokken']],
  ['bottoms', ['pants', 'pant', 'trousers', 'jeans', 'jean', 'shorts', 'short', 'skirt', 'leggings', 'legging', 'joggers', 'jogger', 'chino', 'chinos', 'broek', 'rok', 'hose', 'pantalon', 'jupe']],
  ['outerwear', ['jacket', 'coat', 'parka', 'blazer', 'bomber', 'puffer', 'jas', 'jack', 'mantel', 'jacke', 'veste', 'manteau']],
  ['dresses', ['dress', 'jumpsuit', 'jurk', 'kleid', 'robe']],
];

/** Garment category from a product's type and title; 'tops' when nothing says otherwise. */
export function inferCategory(productType, title) {
  const words = (String(productType || '') + ' ' + String(title || '')).toLowerCase().split(/[^a-zà-ÿ]+/).filter(Boolean);
  for (const [category, list] of CATEGORY_WORDS) {
    if (words.some((w) => list.includes(w))) return category;
  }
  return 'tops';
}

/** Feet + inches -> cm, pounds -> kg (the form accepts either unit system). */
export function toMetric(units, height, heightInches, weight) {
  if (units !== 'imperial') return { height: num(height), weight: num(weight) };
  const ft = num(height) || 0;
  const inch = num(heightInches) || 0;
  const lb = num(weight);
  return { height: Math.round((ft * 12 + inch) * 2.54 * 10) / 10, weight: lb == null ? null : Math.round(lb * 0.45359237 * 10) / 10 };
}
