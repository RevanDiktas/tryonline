"""The measurement pipeline (2026-11-24): framed front + side masks + height + weight + gender -> 14 measurements.

GENERATED by .local_prototype/measure_ml/make_worker_pipeline.py from the source of the scored functions.
Do not edit by hand; change the sources and regenerate.

    mask pair -> locator + width profiles (pipe_profiles2.features)
              -> ridge model on armpit-aligned profiles  +  specialist networks (torso, arms, legs), averaged
The height + weight + gender regression is the starting point; the photos add what they show.
A side photo is REQUIRED (the models were trained with one); the caller falls back to another model without it.
"""
import hashlib, json
from pathlib import Path
import numpy as np, torch, torch.nn as nn

MEASUREMENTS = ['ankle', 'arm-length', 'bicep', 'calf', 'chest', 'forearm', 'height', 'hip', 'leg-length', 'shoulder-breadth', 'shoulder-to-crotch', 'thigh', 'waist', 'wrist']
N_TORSO, N_ARM, N_LEG, N_SIDE = 160, 64, 96, 192
SCALARS = ['cm_per_px', 'crotch_h', 'armpitL_h', 'armpitR_h', 'armL_len', 'armR_len', 'armL_ang', 'armR_ang', 'legL_ang', 'legR_ang', 'side_ratio', 'side_cut', 'armL_ok', 'armR_ok', 'crotch_ok', 'side_ok']
N_PROFILE = 2 * N_TORSO + 2 * N_ARM + 2 * N_LEG + 3 * N_SIDE
TORSO_END, LEG_START = 0.4, 0.5
GROUPS = {'torso': ['chest', 'waist', 'hip', 'shoulder-breadth', 'shoulder-to-crotch'], 'arms': ['bicep', 'forearm', 'wrist', 'arm-length'], 'legs': ['thigh', 'calf', 'ankle', 'leg-length', 'height']}
SEG = [("torso", 2, N_TORSO), ("arms", 2, N_ARM), ("legs", 2, N_LEG), ("side", 3, N_SIDE)]
OFF = np.arange(-6, 52, 1.0)
SO = 2 * N_TORSO + 2 * N_ARM + 2 * N_LEG
SC_100 = [SCALARS.index(k) for k in ("crotch_h", "armpitL_h", "armpitR_h", "armL_len", "armR_len")]
SEG_SLICES = []
_o = 0
for _n, _c, _l in SEG:
    SEG_SLICES.append((_n, _c, _l, _o)); _o += _c * _l

def row_runs(row, min_len=3):
    d = np.diff(np.r_[0, row.astype(np.int8), 0]); s, e = np.flatnonzero(d == 1), np.flatnonzero(d == -1) - 1
    k = (e - s + 1) >= min_len
    return list(zip(s[k].tolist(), e[k].tolist()))


def resample(v, n):
    v = np.asarray(v, float)
    if len(v) < 2:
        return np.zeros(n, np.float32)
    return np.interp(np.linspace(0, len(v) - 1, n), np.arange(len(v)), v).astype(np.float32)


def limb(track, s):
    """track: list of (y, start, end) down one limb. Returns widths across the limb (cm), its length (cm), slant (rad)."""
    if len(track) < 12:
        return np.zeros(0), 0.0, 0.0
    y = np.array([t[0] for t in track], float); c = np.array([(t[1] + t[2]) / 2 for t in track]); w = np.array([t[2] - t[1] + 1 for t in track], float)
    k = 21; cs = np.convolve(np.pad(c, k // 2, mode="edge"), np.ones(k) / k, "valid")
    slope = np.gradient(cs, y)                                # sideways px per row
    cos = 1 / np.sqrt(1 + slope ** 2)                         # a row cuts a slanted limb wider than it is
    return w * cos * s, float(np.sum(1 / cos[:-1] * np.diff(y)) * s), float(np.arctan(np.polyfit(y, c, 1)[0]))


def _overlap(t, a):
    return min(t[1], a[1]) - max(t[0], a[0]) + 1


def front_parts(a):
    rows = np.flatnonzero(a.sum(1) >= 3)
    if len(rows) < 200:
        return None
    top, bot = int(rows[0]), int(rows[-1]); H = bot - top + 1
    R = {y: row_runs(a[y]) for y in range(top, bot + 1)}
    # --- legs, from the floor up: the highest row in the knee-to-shin band that shows two separate legs
    start = None
    for y in range(bot - int(0.36 * H), bot - int(0.08 * H)):
        big = sorted(R[y], key=lambda t: t[0] - t[1])[:2]
        if len(big) < 2: continue
        w1, w2 = sorted(t[1] - t[0] + 1 for t in big); gap = max(t[0] for t in big) - min(t[1] for t in big)
        # two legs: both a real width, of similar width (a hanging arm beside joined legs is not), and close together
        if w1 >= 0.04 * H and w1 >= 0.5 * w2 and gap <= 0.15 * H:
            start = (y, sorted(big)); break
    if start is None:
        return None
    y0, (curL, curR) = start; legs = {"L": [(y0, *curL)], "R": [(y0, *curR)]}; crotch = None
    for y in range(y0 - 1, top, -1):
        oL = [t for t in R[y] if _overlap(t, curL) > 0]; oR = [t for t in R[y] if _overlap(t, curR) > 0]
        if not oL or not oR:
            crotch = y + 1; break
        tL = max(oL, key=lambda t: _overlap(t, curL)); tR = max(oR, key=lambda t: _overlap(t, curR))
        if tL == tR:                                              # the two legs have joined
            crotch = y + 1; break
        tL = (max(tL[0], curL[0] - 4), tL[1]); tR = (tR[0], min(tR[1], curR[1] + 4))   # a hand on the thigh must not widen the leg
        curL, curR = tL, tR; legs["L"].append((y, *tL)); legs["R"].append((y, *tR))
    if crotch is None:
        return None
    downL, downR = legs["L"][0][1:], legs["R"][0][1:]
    for y in range(y0 + 1, bot + 1):                              # and down to the feet
        oL = [t for t in R[y] if _overlap(t, downL) > 0]; oR = [t for t in R[y] if _overlap(t, downR) > 0]
        if oL: downL = max(oL, key=lambda t: _overlap(t, downL)); legs["L"].append((y, *downL))
        if oR: downR = max(oR, key=lambda t: _overlap(t, downR)); legs["R"].append((y, *downR))
    for k in legs: legs[k].sort()
    cx = (legs["L"][0][2] + legs["R"][0][1]) / 2                 # midline: between the legs at the crotch
    # --- the central run (torso, plus whatever touches it) for every row above the crotch
    central = {}; prev = (legs["L"][0][1], legs["R"][0][2])
    for y in range(crotch - 1, top - 1, -1):
        if not R[y]: break
        t = max(R[y], key=lambda t: _overlap(t, prev) if _overlap(t, prev) > 0 else -abs((t[0] + t[1]) / 2 - cx) - 1e6)
        central[y] = t; prev = t
    # --- arms: runs lying wholly outside the central run (outside the leg, below the crotch)
    arms = {"L": [], "R": []}; pit = {"L": None, "R": None}
    legrow = {k: {t[0]: t for t in legs[k]} for k in legs}
    for side in "LR":
        seq = []
        for y in range(top + int(0.12 * H), bot + 1):
            if y in central: inner = central[y][0] if side == "L" else central[y][1]
            elif y in legrow[side]: inner = legrow[side][y][1] if side == "L" else legrow[side][y][2]
            else: continue
            c = [t for t in R[y] if (t[1] < inner if side == "L" else t[0] > inner)]
            if c: seq.append((y, *(c[0] if side == "L" else c[-1])))
        # the arm is the longest stretch of such rows (short breaks allowed where the arm touches the body)
        best, cur = [], []
        for t in seq:
            if cur and t[0] - cur[-1][0] > 25:
                if len(cur) > len(best): best = cur
                cur = []
            cur.append(t)
        if len(cur) > len(best): best = cur
        if len(best) >= 0.10 * H:
            arms[side] = best; pit[side] = best[0][0]
    # --- torso edges: the central run, bridged across rows where an arm touches it
    edges = {}
    for side, idx in (("L", 0), ("R", 1)):
        e = {y: central[y][idx] for y in central}
        if pit[side] is not None:
            armrows = {t[0] for t in arms[side]}; lo, hi = pit[side], arms[side][-1][0]
            free = sorted(y for y in e if lo <= y <= hi and y in armrows)        # arm separate here: edge is the torso's own
            touch = [y for y in e if lo <= y <= hi and y not in armrows]
            if free and touch:
                e.update(zip(touch, np.interp(touch, free, [e[y] for y in free]).round().astype(int)))
        for y, v in e.items():
            edges.setdefault(y, [0, 0])[idx] = int(v)
    edges = {y: tuple(v) for y, v in edges.items()}
    return {"top": top, "bot": bot, "H": H, "edges": edges, "pit": pit, "crotch": crotch, "legs": legs, "arms": arms,
            "extent": {y: (R[y][0][0], R[y][-1][1]) for y in R if R[y]}}


def features(front, side, height_cm, side_ratio=None):
    """Same return as pipe_profiles.features: (profile float32 [N_PROFILE], scalars float32 [len(SCALARS)]) or None."""
    P = front_parts(front)
    if P is None:
        return None
    s = height_cm / P["H"]; top, bot, H = P["top"], P["bot"], P["H"]; crotch = P["crotch"]
    legrow = {k: {t[0]: t for t in P["legs"][k]} for k in "LR"}
    def torso_w(y):
        if y in P["edges"]: return (P["edges"][y][1] - P["edges"][y][0] + 1) * s
        if y in legrow["L"] and y in legrow["R"]: return (legrow["R"][y][2] - legrow["L"][y][1] + 1) * s     # below the crotch: outer edge to outer edge
        return (P["extent"][y][1] - P["extent"][y][0] + 1) * s if y in P["extent"] else 0.0
    torso = [torso_w(y) for y in range(top, bot - int(TORSO_END * H) + 1)]
    extent = [(P["extent"][y][1] - P["extent"][y][0] + 1) * s if y in P["extent"] else 0.0 for y in range(top, bot + 1)]
    out, sc = [resample(torso, N_TORSO), resample(extent, N_TORSO)], {k: 0.0 for k in SCALARS}
    for k in "LR":
        w, ln, ang = limb(P["arms"][k], s)
        out.append(resample(w, N_ARM)); sc[f"arm{k}_len"], sc[f"arm{k}_ang"], sc[f"arm{k}_ok"] = ln, ang, float(len(w) > 0)
    for k in "LR":
        tr = [t for t in P["legs"][k] if t[0] >= crotch]; w, ln, ang = limb(tr, s); sc[f"leg{k}_ang"] = ang
        ys = [t[0] for t in tr]; wd = dict(zip(ys, w)) if len(w) else {}
        prof = []
        for y in range(bot - int(LEG_START * H), bot + 1):
            if y in wd: prof.append(wd[y])
            elif y < crotch and y in P["edges"]: prof.append((P["edges"][y][1] - P["edges"][y][0] + 1) * s / 2)   # thighs joined: half each
            else: prof.append(0.0)
        out.append(resample(prof, N_LEG))
    sc["cm_per_px"] = s; sc["crotch_ok"] = 1.0; sc["crotch_h"] = (bot - crotch) * s
    for k in "LR":
        sc[f"armpit{k}_h"] = (bot - P["pit"][k]) * s if P["pit"][k] else 0.0
    srows = np.flatnonzero(side.sum(1) >= 3) if side is not None else []
    if len(srows) >= 200:
        st, sb = int(srows[0]), int(srows[-1]); cut = sb >= side.shape[0] - 2
        # feet out of frame: the side photo's pixel height comes from pipe_side_scale.py (side_ratio = side / front
        # pixel height) when given; otherwise the front photo's scale is borrowed, as before
        Hs = (max(int(round(side_ratio * H)), sb - st + 1) if side_ratio else H) if cut else sb - st + 1; ss = height_cm / Hs
        band = side[st + int(0.3 * Hs):st + int(0.5 * Hs)]; cx = np.flatnonzero(band.sum(0)).mean() if band.any() else side.shape[1] / 2
        w, fe, be = [], [], []
        for y in range(st, st + Hs):
            r = row_runs(side[y]) if y < side.shape[0] else []
            if r:
                t = max(r, key=lambda t: t[1] - t[0]); w.append((t[1] - t[0] + 1) * ss); fe.append((t[0] - cx) * ss); be.append((t[1] - cx) * ss)
            else:
                w.append(0.0); fe.append(0.0); be.append(0.0)
        out += [resample(w, N_SIDE), resample(fe, N_SIDE), resample(be, N_SIDE)]
        sc["side_ratio"], sc["side_cut"], sc["side_ok"] = (Hs if cut and side_ratio else sb - st + 1) / H, float(cut), 1.0
    else:
        out += [np.zeros(N_SIDE, np.float32)] * 3
    return np.concatenate(out), np.array([sc[k] for k in SCALARS], np.float32)


def meta(male, h, w):
    bmi = w / (h / 100) ** 2
    return np.stack([male, (h - 170) / 10, (w - 75) / 15, (bmi - 25) / 5, male * (h - 170) / 10, male * (w - 75) / 15,
                     ((h - 170) / 10) ** 2, ((w - 75) / 15) ** 2, (h - 170) / 10 * (w - 75) / 15], 1).astype(np.float32)


class Enc(nn.Module):
    def __init__(self, c_in, width=48):
        super().__init__()
        L, c = [], c_in
        for k, (co, st) in enumerate([(width, 1), (width, 2), (width * 2, 2), (width * 2, 2)]):
            L += [nn.Conv1d(c, co, 5, stride=st, padding=2, bias=False), nn.BatchNorm1d(co), nn.ReLU(inplace=True)]; c = co
        self.net = nn.Sequential(*L); self.pool = nn.AdaptiveAvgPool1d(8); self.out = width * 2 * 8

    def forward(self, x):
        return self.pool(self.net(x)).flatten(1)       # keeps WHERE along the part each width sits


class Specialist(nn.Module):
    def __init__(self, n_extra, n_out):
        super().__init__()
        self.enc = nn.ModuleDict({name: Enc(c) for name, c, _ in SEG})
        self.mlp = nn.Sequential(nn.Linear(sum(e.out for e in self.enc.values()) + n_extra, 256), nn.ReLU(inplace=True), nn.Dropout(0.2),
                                 nn.Linear(256, 128), nn.ReLU(inplace=True), nn.Linear(128, n_out))

    def forward(self, segs, extra):
        return self.mlp(torch.cat([self.enc[n](segs[n]) for n, _, _ in SEG] + [extra], 1))


def extra(p):
    sc = p["sca"].copy(); sc[:, [SCALARS.index(k) for k in ("crotch_h", "armpitL_h", "armpitR_h", "armL_len", "armR_len")]] /= 100
    return np.c_[meta(p["male"], p["h"], p["w"]), sc].astype(np.float32)


def aligned(p):
    h = p["h"].astype(np.float64); pr = p["prof"].astype(np.float64); n = len(h)
    pl, prr = p["sca"][:, SCALARS.index("armpitL_h")], p["sca"][:, SCALARS.index("armpitR_h")]
    pit = np.where((pl > 0) & (prr > 0), (pl + prr) / 2, np.maximum(pl, prr)); pit = np.where(pit > 0, pit, 0.76 * h)   # cm above floor
    tw, sw = np.zeros((n, len(OFF))), np.zeros((n, len(OFF)))
    for i in range(n):
        z = h[i] - (pit[i] - OFF)                               # cm below head top
        tw[i] = np.interp(z, np.arange(N_TORSO) * (0.6 * h[i] / (N_TORSO - 1)), pr[i, :N_TORSO])
        sw[i] = np.interp(z, np.arange(N_SIDE) * (h[i] / (N_SIDE - 1)), pr[i, SO:SO + N_SIDE])
    a, b = tw / 2, sw / 2; ell = np.pi * (3 * (a + b) - np.sqrt((3 * a + b) * (a + 3 * b)))
    return tw, sw, ell, pit


def feats(p, variant):
    base = np.c_[p["prof"] / 20, extra(p)]
    if variant == "base": X = base
    else:
        tw, sw, ell, pit = aligned(p); has_side = (p["sca"][:, SCALARS.index("side_ok")] > 0)[:, None]
        add = [tw / 20, sw / 20 * has_side, (pit / p["h"])[:, None]] + ([ell / 80 * has_side] if "ell" in variant else [])
        X = np.c_[np.c_[tuple(add)], extra(p)] if variant.startswith("only") else np.c_[base, np.c_[tuple(add)]]
    return np.c_[X, X * p["male"][:, None]]


def meta_t(male, h, w):
    bmi = w / (h / 100) ** 2; H, W = (h - 170) / 10, (w - 75) / 15
    return torch.stack([male, H, W, (bmi - 25) / 5, male * H, male * W, H ** 2, W ** 2, H * W], 1)


def inputs(prof, sca, male, h, w):
    segs = {n: prof[:, o:o + c * l].reshape(len(prof), c, l) / 20 for n, c, l, o in SEG_SLICES}
    sc = sca.clone(); sc[:, SC_100] = sc[:, SC_100] / 100
    return segs, torch.cat([meta_t(male, h, w), sc], 1)


class PipelineModel:
    """Same interface as model.SilhouetteModel: predict() takes framed 960 x 720 masks (uint8 0/255), returns cm."""

    def __init__(self, checkpoint_path, device="cpu"):
        p = Path(checkpoint_path); ck = torch.load(p, map_location="cpu", weights_only=False)
        self.measurements = list(ck["measurements"]); assert self.measurements == MEASUREMENTS
        self.ridge = ck["ridge"]; self.nets = []
        for m in ck["nets"]:
            nets = {}
            for g, names in GROUPS.items():
                cols = [MEASUREMENTS.index(n) for n in names]; net = Specialist(9 + len(SCALARS), len(cols)); net.load_state_dict(m["states"][g]); nets[g] = (cols, net.eval())
            self.nets.append({"nets": nets, "coef": np.asarray(m["coef"], np.float64), "rstd": np.asarray(m["rstd"], np.float64)})
        self.coef = np.asarray(self.ridge["coef"], np.float64)
        self.sha256 = hashlib.sha256(p.read_bytes()).hexdigest(); side = p.with_suffix(".json")
        self.info = json.loads(side.read_text()) if side.exists() else {}
        self.version = self.info.get("version", "unknown") + "@" + self.sha256[:12]
        self.sidecar_matches = self.info.get("sha256") in (None, self.sha256)

    def prior(self, male, height_cm, weight_kg):
        m = meta(np.array([float(male)]), np.array([float(height_cm)]), np.array([float(weight_kg)]))
        return dict(zip(self.measurements, (np.c_[m, np.ones(1)] @ self.coef)[0].tolist()))

    def profiles(self, front_masks, side_masks, height_cm):
        """One (profile, scalars) row per readable front mask; front i goes with side i (the last side is reused)."""
        rows = []
        for i, f in enumerate(front_masks):
            r = features(np.asarray(f) > 127, np.asarray(side_masks[min(i, len(side_masks) - 1)]) > 127, float(height_cm))
            if r is not None and r[1][SCALARS.index("side_ok")] > 0: rows.append(r)
        return rows

    def predict_rows(self, rows, male, height_cm, weight_kg):
        n = len(rows); p = {"prof": np.stack([r[0] for r in rows]), "sca": np.stack([r[1] for r in rows]), "male": np.full(n, float(male)),
                            "h": np.full(n, float(height_cm)), "w": np.full(n, float(weight_kg))}
        M = np.c_[meta(p["male"], p["h"], p["w"]), np.ones(n)]; preds = []
        r = self.ridge; X = feats(p, str(r["variant"])); preds.append(M @ r["coef"] + (np.c_[(X - r["mu"]) / r["sd"], np.ones(n)] @ r["W"]) * r["rstd"])
        T = lambda v: torch.from_numpy(np.asarray(v, np.float32))
        for m in self.nets:
            b = M @ m["coef"]; pred = b.copy(); segs, ex = inputs(T(p["prof"]), T(p["sca"]), T(p["male"]), T(p["h"]), T(p["w"]))
            with torch.no_grad():
                for g, (cols, net) in m["nets"].items():
                    pred[:, cols] = b[:, cols] + net(segs, ex).numpy().astype(np.float64) * m["rstd"][cols]
            preds.append(pred)
        return np.mean([q.mean(0) for q in preds], 0)

    def predict(self, front_masks, side_masks, male, height_cm, weight_kg):
        if not front_masks or not side_masks: raise ValueError("the pipeline model needs at least one front and one side mask")
        rows = self.profiles(front_masks, side_masks, height_cm)
        if not rows: raise ValueError("could not locate the body parts in the front outline")
        return dict(zip(self.measurements, self.predict_rows(rows, male, height_cm, weight_kg).tolist()))
