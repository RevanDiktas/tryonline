def meta(male, h, w):
    bmi = w / (h / 100) ** 2
    return np.stack([male, (h - 170) / 10, (w - 75) / 15, (bmi - 25) / 5, male * (h - 170) / 10, male * (w - 75) / 15,
                     ((h - 170) / 10) ** 2, ((w - 75) / 15) ** 2, (h - 170) / 10 * (w - 75) / 15], 1).astype(np.float32)


# ================================================================ from pipe_specialists.py
def split_profile(p):
    """flat profile -> dict of (B, channels, length) arrays, in units of 20 cm."""
    out, o = {}, 0
    for name, c, n in SEG:
        out[name] = (p[:, o:o + c * n].reshape(len(p), c, n) / 20).astype(np.float32); o += c * n
    return out


import torch, torch.nn as nn


class Enc(nn.Module):
    def __init__(self, c_in, width=48):
        super().__init__()
        L, c = [], c_in
        for k, (co, st) in enumerate([(width, 1), (width, 2), (width * 2, 2), (width * 2, 2)]):
            L += [nn.Conv1d(c, co, 5, stride=st, padding=2, bias=False), nn.BatchNorm1d(co), nn.ReLU(inplace=True)]; c = co
        self.net = nn.Sequential(*L); self.pool = nn.AdaptiveAvgPool1d(8); self.out = width * 2 * 8

    def forward(self, x):
        return self.pool(self.net(x)).flatten(1)       # keeps WHERE along the part each width sits


# ================================================================ from train_street.py
M = lambda p: np.c_[meta(p["male"], p["h"], p["w"]), np.ones(len(p["h"]))]


def limb_x(p):
    """Bare-limb widths (cm / 10) and their availability flags; widths also relative to height."""
    L = p["limb"]; n = L.shape[1] // 2; v, ok = L[:, :n], L[:, n:]; return np.c_[v / 10, ok, v / p["h"][:, None] * 10]


def cnn_meta(p):
    return np.c_[meta(p["male"], p["h"], p["w"]), limb_x(p)] if "limb" in p else meta(p["male"], p["h"], p["w"])


def seq_x(p, noise=None):
    """(n, 12, N_ROW): six width signals (cm / 20) and six cloth flags down the body."""
    n = len(p["h"]); R = p["rows"].reshape(n, ROW_CH, -1) / 20; R[:, 3] *= 2          # runs: 10 per run -> 1 per run
    c = p["cover"].reshape(n, 6, -1).copy() if "cover" in p else np.zeros((n, 6, R.shape[2]), np.float32)
    if noise is not None:                                                                # a real parser is wrong on about 1 row in 10, in stretches
        for i in np.flatnonzero(noise.random(n) < 0.7):
            for _ in range(int(noise.integers(1, 4))): a = int(noise.integers(0, R.shape[2] - 12)); ch = int(noise.integers(0, 6)); c[i, ch, a:a + int(noise.integers(3, 12))] = noise.integers(0, 2)
    if "torso" in p:
        t = p["torso"].reshape(n, 2, -1) / 20
        if noise is not None:                                                            # the parser misses a bare arm on some photos, or on a stretch of rows
            miss = noise.random(n) < 0.08; t = np.where(miss[:, None, None], np.stack([R[:, 2], np.zeros_like(R[:, 2])], 1), t)
        return np.concatenate([R, c, t], 1).astype(np.float32)
    return np.concatenate([R, c], 1).astype(np.float32)


def make_seq(n_meta, n_out, width=64):
    import torch, torch.nn as nn
    class Net(nn.Module):
        def __init__(s):
            super().__init__(); L, c_in = [], 14 if globals().get("USE_TORSO") else 12
            for c, st in ((width, 1), (width, 2), (width * 2, 2), (width * 2, 2)):
                L += [nn.Conv1d(c_in, c, 5, stride=st, padding=2, bias=False), nn.BatchNorm1d(c), nn.ReLU(inplace=True)]; c_in = c
            s.enc = nn.Sequential(*L, nn.AdaptiveAvgPool1d(8), nn.Flatten()); s.head = nn.Sequential(nn.Linear(c_in * 8 + n_meta, 256), nn.ReLU(inplace=True), nn.Dropout(0.15), nn.Linear(256, n_out))
        def forward(s, x, m): return s.head(torch.cat([s.enc(x), m], 1))
    return Net()


def pred_seq(m, p):
    import torch
    b = M(p) @ m["coef"]; Mt = np.c_[cnn_meta(p), np.zeros(len(p["h"]))].astype(np.float32)
    with torch.no_grad(): r = m["net"](torch.from_numpy(seq_x(p)), torch.from_numpy(Mt)).numpy()
    return b + r * m["rstd"], b


def both_x(p, noise=None):
    segs = split_profile(np.where((p["sca"][:, :1] > 0), p["prof"], 0)); sc = p["sca"].copy(); sc[:, [SCALARS.index(k) for k in ("crotch_h", "armpitL_h", "armpitR_h", "armL_len", "armR_len")]] /= 100
    return seq_x(p, noise), segs, np.c_[cnn_meta(p), sc].astype(np.float32)


def make_both(n_meta, n_out, width=64):
    import torch, torch.nn as nn
    class Net(nn.Module):
        def __init__(s):
            super().__init__(); s.seq = make_seq(0, 1, width).enc; s.enc = nn.ModuleDict({name: Enc(c) for name, c, _ in SEG}); s.drop = nn.Dropout(0.15)
            s.head = nn.Sequential(nn.Linear(width * 2 * 8 + sum(e.out for e in s.enc.values()) + n_meta, 384), nn.ReLU(inplace=True), nn.Dropout(0.2), nn.Linear(384, 128), nn.ReLU(inplace=True), nn.Linear(128, n_out))
        def forward(s, x, segs, m): return s.head(torch.cat([s.drop(s.seq(x))] + [s.drop(s.enc[n](segs[n])) for n, _, _ in SEG] + [m], 1))
    return Net()


def pred_both(m, p):
    import torch
    b = M(p) @ m["coef"]; X, G, E = both_x(p); E = np.c_[E, np.zeros(len(E), np.float32)]; out = []
    with torch.no_grad():
        for i in range(0, len(E), 512): out.append(m["net"](torch.from_numpy(X[i:i + 512]), {k: torch.from_numpy(v[i:i + 512]) for k, v in G.items()}, torch.from_numpy(E[i:i + 512])).numpy())
    return b + np.concatenate(out) * m["rstd"], b


def tape_prior(male, h, w):
    """Height + weight + gender estimate in TAPE definitions (fitted on 6,068 tape-measured ANSUR II people): chest, waist, hip, thigh."""
    C = np.load(TAPE_PRIOR)["C"]; bmi = w / (h / 100) ** 2
    return np.c_[np.ones(len(h)), male, h, w, bmi, male * h, male * w, male * bmi, w ** 0.5, male * w ** 0.5] @ C


def to_tape(pred, base, p):
    """Keeps what the photos added (prediction minus the BodyM-definition estimate) and re-anchors it on the tape-definition estimate."""
    out = pred.copy(); tp = tape_prior(p["male"], p["h"], p["w"])
    for c, k in enumerate(("chest", "waist", "hip", "thigh")): j = MEASUREMENTS.index(k); out[:, j] = tp[:, c] + (pred[:, j] - base[:, j])
    return out


